/* 一行 / 一列导线的元组链(先横后竖的局部版本,方向自动判断) */
const h = (y, x0, x1) => {
  const out = []
  const d = x1 > x0 ? 1 : -1
  for (let x = x0; x !== x1; x += d) out.push([T.WIRE, x, y, x + d, y])
  return out
}
const v = (x, y0, y1) => {
  const out = []
  const d = y1 > y0 ? 1 : -1
  for (let y = y0; y !== y1; y += d) out.push([T.WIRE, x, y, x, y + d])
  return out
}

